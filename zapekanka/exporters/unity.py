"""Unity export: FBX + textures into the project + an editor script that
configures texture importers and creates materials (URP, HDRP, Built-in)."""

import os

import bpy

from . import common
from ..core.maps import expand_channels

EDITOR_SCRIPT = r'''// Generated by Zapekanka (Blender). Safe to keep in the project: it only acts on
// assets that have a matching *.zapekanka-unity.json manifest next to them.
#if UNITY_EDITOR
using System;
using System.IO;
using UnityEditor;
using UnityEngine;

namespace Zapekanka
{
    [Serializable] public class TextureInfo { public string file; public string kind; public bool srgb; public bool alpha; }
    [Serializable] public class SetInfo
    {
        public string name; public string model; public string material; public string modelMaterial;
        public string pipeline; public string normalFormat; public TextureInfo[] textures;
    }

    public class ZapekankaPostprocessor : AssetPostprocessor
    {
        static SetInfo LoadManifest(string folder, out string manifestPath)
        {
            manifestPath = null;
            if (!Directory.Exists(folder)) return null;
            foreach (var path in Directory.GetFiles(folder, "*.zapekanka-unity.json"))
            {
                manifestPath = path.Replace('\\', '/');
                return JsonUtility.FromJson<SetInfo>(File.ReadAllText(path));
            }
            return null;
        }

        static TextureInfo FindTexture(string assetPath)
        {
            var folder = Path.GetDirectoryName(assetPath);
            var parent = Path.GetDirectoryName(folder);
            foreach (var dir in new[] { folder, parent })
            {
                if (string.IsNullOrEmpty(dir)) continue;
                string manifestPath;
                var set = LoadManifest(dir, out manifestPath);
                if (set == null || set.textures == null) continue;
                var file = Path.GetFileName(assetPath);
                foreach (var t in set.textures) if (t.file == file) return t;
            }
            return null;
        }

        void OnPreprocessTexture()
        {
            var info = FindTexture(assetPath);
            if (info == null) return;
            var ti = (TextureImporter)assetImporter;
            if (info.kind == "normal")
            {
                ti.textureType = TextureImporterType.NormalMap;
                ti.sRGBTexture = false;
            }
            else
            {
                ti.textureType = TextureImporterType.Default;
                ti.sRGBTexture = info.srgb;
                ti.alphaSource = info.alpha ? TextureImporterAlphaSource.FromInput : TextureImporterAlphaSource.None;
                ti.alphaIsTransparency = info.alpha && info.kind == "base_color";
            }
            ti.mipmapEnabled = true;
        }

        static void OnPostprocessAllAssets(string[] imported, string[] deleted, string[] moved, string[] movedFrom)
        {
            foreach (var path in imported)
            {
                if (!path.EndsWith(".zapekanka-unity.json")) continue;
                EditorApplication.delayCall += () => Build(path);
            }
        }

        static Shader PickShader(string pipeline)
        {
            string[] names = pipeline == "HDRP" ? new[] { "HDRP/Lit" }
                : pipeline == "URP" ? new[] { "Universal Render Pipeline/Lit" } : new[] { "Standard" };
            foreach (var n in names) { var s = Shader.Find(n); if (s != null) return s; }
            return Shader.Find("Standard");
        }

        static void Build(string manifestPath)
        {
            var set = JsonUtility.FromJson<SetInfo>(File.ReadAllText(manifestPath));
            var folder = Path.GetDirectoryName(manifestPath).Replace('\\', '/');
            var shader = PickShader(set.pipeline);
            var matPath = folder + "/" + set.material + ".mat";
            var mat = AssetDatabase.LoadAssetAtPath<Material>(matPath);
            if (mat == null) { mat = new Material(shader); AssetDatabase.CreateAsset(mat, matPath); }
            else mat.shader = shader;
            bool hdrp = set.pipeline == "HDRP", urp = set.pipeline == "URP";
            foreach (var t in set.textures)
            {
                var tex = AssetDatabase.LoadAssetAtPath<Texture2D>(folder + "/Textures/" + t.file);
                if (tex == null) continue;
                switch (t.kind)
                {
                    case "base_color":
                        mat.SetTexture(hdrp ? "_BaseColorMap" : urp ? "_BaseMap" : "_MainTex", tex);
                        if (t.alpha)
                        {
                            mat.SetFloat("_AlphaClip", 1f); mat.SetFloat("_AlphaCutoffEnable", 1f);
                            mat.EnableKeyword("_ALPHATEST_ON");
                        }
                        break;
                    case "normal":
                        mat.SetTexture(hdrp ? "_NormalMap" : "_BumpMap", tex);
                        mat.EnableKeyword(hdrp ? "_NORMALMAP_TANGENT_SPACE" : "_NORMALMAP");
                        if (hdrp) mat.EnableKeyword("_NORMALMAP");
                        break;
                    case "metallic_smoothness":
                        mat.SetTexture("_MetallicGlossMap", tex);
                        mat.EnableKeyword(urp ? "_METALLICSPECGLOSSMAP" : "_METALLICGLOSSMAP");
                        mat.SetFloat("_Smoothness", 1f); mat.SetFloat("_GlossMapScale", 1f);
                        break;
                    case "mask":
                        mat.SetTexture("_MaskMap", tex); mat.EnableKeyword("_MASKMAP");
                        break;
                    case "ao":
                        mat.SetTexture("_OcclusionMap", tex); mat.EnableKeyword("_OCCLUSIONMAP");
                        break;
                    case "emission":
                        mat.SetTexture(hdrp ? "_EmissiveColorMap" : "_EmissionMap", tex);
                        mat.SetColor(hdrp ? "_EmissiveColor" : "_EmissionColor", Color.white);
                        mat.EnableKeyword(hdrp ? "_EMISSIVE_COLOR_MAP" : "_EMISSION");
                        mat.globalIlluminationFlags = MaterialGlobalIlluminationFlags.BakedEmissive;
                        break;
                }
            }
            EditorUtility.SetDirty(mat);
            AssetDatabase.SaveAssets();
            if (!string.IsNullOrEmpty(set.model))
            {
                var modelPath = folder + "/" + set.model;
                var importer = AssetImporter.GetAtPath(modelPath) as ModelImporter;
                if (importer != null)
                {
                    importer.materialImportMode = ModelImporterMaterialImportMode.ImportStandard;
                    importer.AddRemap(new AssetImporter.SourceAssetIdentifier(typeof(Material), set.modelMaterial), mat);
                    importer.SaveAndReimport();
                }
            }
            Debug.Log("Zapekanka: material " + set.material + " ready");
        }
    }
}
#endif
'''


def _kind(f):
    chans = expand_channels(f["channels"])
    keys = [c.map for c in chans]
    if f["id"] in ("normal", "metallic_smoothness", "mask", "emission", "ao"):
        return f["id"]
    if keys[:3] == ["base_color"] * 3:
        return "base_color"
    return f["id"]


def export(context, sets, root, report):
    s = context.scene.zapekanka
    e = s.export
    raw = e.unity_project.strip()
    project = os.path.normpath(bpy.path.abspath(raw)) if raw else ""
    if project and os.path.isdir(os.path.join(project, "Assets")):
        assets_root = os.path.join(project, "Assets", e.unity_folder or "Zapekanka")
        editor_dir = os.path.join(project, "Assets", "Editor", "Zapekanka")
    else:
        if e.unity_project.strip():
            report({"WARNING"}, "Not a Unity project (no Assets folder): exporting to the export folder")
        assets_root = os.path.join(root, "Assets", e.unity_folder or "Zapekanka")
        editor_dir = os.path.join(root, "Assets", "Editor", "Zapekanka")
    os.makedirs(editor_dir, exist_ok=True)
    with open(os.path.join(editor_dir, "ZapekankaPostprocessor.cs"), "w", encoding="utf-8") as fh:
        fh.write(EDITOR_SCRIPT)
    for ts in sets:
        folder = os.path.join(assets_root, ts.name)
        os.makedirs(folder, exist_ok=True)
        files = common.copy_textures(ts, os.path.join(folder, "Textures")) if e.include_textures else []
        mat = common.baked_material(context, ts)
        mesh_name = s.mesh_template.replace("{name}", ts.name)
        model = ""
        if ts.lows:
            groups = [{"name": mesh_name, "objects": ts.lows, "material": mat, "pivot": ts.lows[0]}]
            with common.export_objects(context, groups, e.triangulate) as objs:
                model = mesh_name + ".fbx"
                common.export_fbx(context, objs, os.path.join(folder, model), "UNITY", e.scale, e.triangulate)
        common.write_json(os.path.join(folder, ts.name + ".zapekanka-unity.json"), {
            "name": ts.name,
            "model": model,
            "material": s.material_template.replace("{name}", ts.name),
            "modelMaterial": mat.name if mat is not None else "",
            "pipeline": e.unity_pipeline,
            "normalFormat": s.normal_format,
            "textures": [
                {"file": os.path.basename(f["path"]), "kind": _kind(f), "srgb": bool(f.get("srgb")),
                 "alpha": len(expand_channels(f["channels"])) == 4}
                for f in files
            ],
        })
    if s.normal_format != "OPENGL":
        report({"WARNING"}, "Unity expects OpenGL normal maps; the bake uses DirectX. Use the Unity preset")
    report({"INFO"}, "Exported to %s - Unity sets up materials when it imports the files" % assets_root)
    return assets_root
